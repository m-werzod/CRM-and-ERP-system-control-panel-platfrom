const LESSON_SELECT = {
  id: true,
  branchId: true,
  groupId: true,
  teacherId: true,
  roomId: true,
  subjectId: true,
  scheduleSlotId: true,
  lessonDate: true,
  startsAt: true,
  endsAt: true,
  topic: true,
  lessonNumber: true,
  status: true,
  cancellationReason: true,
  attendanceStatus: true,
  attendanceSubmittedAt: true,
  group: { select: { name: true, code: true } },
  room: { select: { name: true } },
  subject: { select: { name: true } },
  teacher: {
    select: { employee: { select: { user: { select: { firstName: true, lastName: true } } } } },
  },
  _count: { select: { attendanceRecords: true } },
} satisfies Prisma.LessonSelect;

type LessonRow = Prisma.LessonGetPayload<{ select: typeof LESSON_SELECT }>;

export interface LessonSummary {
  readonly id: string;
  readonly branchId: string;
  readonly groupId: string;
  readonly groupName: string;
  readonly groupCode: string;
  readonly teacherId: string | null;
  readonly teacherName: string | null;
  readonly roomId: string | null;
  readonly roomName: string | null;
  readonly subjectId: string | null;
  readonly subjectName: string | null;
  readonly scheduleSlotId: string | null;
  readonly lessonDate: DateOnly;
  readonly startsAt: Date;
  readonly endsAt: Date;
  /** `HH:MM` in the branch timezone. */
  readonly startTime: string;
  readonly endTime: string;
  readonly durationMinutes: number;
  readonly topic: string | null;
  readonly lessonNumber: number | null;
  readonly status: LessonStatus;
  readonly cancellationReason: string | null;
  readonly attendanceStatus: LessonAttendanceStatus;
  readonly registerSubmitted: boolean;
  readonly markedCount: number;
}

export interface LessonDetail extends LessonSummary {
  /** Students whose enrollment was open on the lesson date. */
  readonly enrolledCount: number;
}

function toLessonSummary(row: LessonRow, zone: TimeZone): LessonSummary {
  const teacherUser = row.teacher?.employee.user;
  return {
    id: row.id,
    branchId: row.branchId,
    groupId: row.groupId,
    groupName: row.group.name,
    groupCode: row.group.code,
    teacherId: row.teacherId,
    teacherName: teacherUser ? `${teacherUser.firstName} ${teacherUser.lastName}` : null,
    roomId: row.roomId,
    roomName: row.room?.name ?? null,
    subjectId: row.subjectId,
    subjectName: row.subject?.name ?? null,
    scheduleSlotId: row.scheduleSlotId,
    lessonDate: prismaDateToDateOnly(row.lessonDate),
    startsAt: row.startsAt,
    endsAt: row.endsAt,
    startTime: formatTime(row.startsAt, zone),
    endTime: formatTime(row.endsAt, zone),
    durationMinutes: Math.round((row.endsAt.getTime() - row.startsAt.getTime()) / 60_000),
    topic: row.topic,
    lessonNumber: row.lessonNumber,
    status: row.status,
    cancellationReason: row.cancellationReason,
    attendanceStatus: row.attendanceStatus,
    registerSubmitted:
      row.attendanceStatus === 'SUBMITTED' || row.attendanceStatus === 'APPROVED',
    markedCount: row._count.attendanceRecords,
  };
}

/**
 * One lesson with its roster size.
 *
 * `extraWhere` carries a reader's SELF narrowing. Write paths pass nothing: a
 * teacher who has just created a lesson must be able to read back what they made,
 * and the write already established that they may.
 */
async function loadLessonDetail(
  ctx: AccessContext,
  db: Db,
  lessonId: string,
  extraWhere: Prisma.LessonWhereInput = {},
): Promise<LessonDetail> {
  const row = await db.lesson.findFirst({
    where: { id: lessonId, ...scopeFilter(ctx), ...extraWhere },
    select: LESSON_SELECT,
  });
  if (!row) throw new NotFoundError('Lesson', lessonId);

  const settings = await getSettings(
    ['timezone'],
    { organizationId: ctx.organizationId, branchId: row.branchId },
    db,
  );

  const enrolledCount = await db.enrollment.count({
    where: {
      groupId: row.groupId,
      startDate: { lte: row.lessonDate },
      OR: [{ endDate: null }, { endDate: { gte: row.lessonDate } }],
      student: { deletedAt: null },
    },
  });

  return { ...toLessonSummary(row, settings.timezone), enrolledCount };
}

export interface ListLessonsFilters {
  readonly from?: DateOnly | null;
  readonly to?: DateOnly | null;
  readonly groupId?: string | null;
  readonly teacherId?: string | null;
  readonly roomId?: string | null;
  readonly branchId?: string | null;
  readonly status?: LessonStatus | null;
  readonly attendanceStatus?: LessonAttendanceStatus | null;
  readonly includeCancelled?: boolean;
  readonly page?: number;
  readonly pageSize?: number;
}

export async function listLessons(
  ctx: AccessContext,
  filters: ListLessonsFilters = {},
  db: Db = prisma,
): Promise<{ rows: LessonSummary[]; total: number; page: number; pageSize: number }> {
  requirePermission(ctx, 'schedule.view');

  const page = Math.max(1, filters.page ?? 1);
  const pageSize = Math.min(100, Math.max(1, filters.pageSize ?? 50));

  const settings = await getSettings(
    ['timezone'],
    { organizationId: ctx.organizationId, branchId: filters.branchId ?? null },
    db,
  );

  const where: Prisma.LessonWhereInput = {
    ...(composeReadFilter(ctx, {
      selfFilter: teacherLessonFilter(ctx),
      escapeHatch: 'schedule.viewAll',
    }) as object),
    ...(filters.branchId ? { branchId: filters.branchId } : {}),
    ...(filters.groupId ? { groupId: filters.groupId } : {}),
    ...(filters.teacherId ? { teacherId: filters.teacherId } : {}),
    ...(filters.roomId ? { roomId: filters.roomId } : {}),
    ...(filters.status ? { status: filters.status } : {}),
    ...(filters.attendanceStatus ? { attendanceStatus: filters.attendanceStatus } : {}),
    ...(filters.status || filters.includeCancelled ? {} : { status: { not: 'CANCELLED' } }),
    // Filtered on the indexed calendar column rather than on the instants, which
    // is what makes "this week's lessons" a range scan.
    ...(filters.from || filters.to
      ? {
          lessonDate: {
            ...(filters.from ? { gte: dateOnlyToPrismaDate(filters.from) } : {}),
            ...(filters.to ? { lte: dateOnlyToPrismaDate(filters.to) } : {}),
          },
        }
      : {}),
  };

  const [rows, total] = await Promise.all([
    db.lesson.findMany({
      where,
      orderBy: [{ lessonDate: 'asc' }, { startsAt: 'asc' }],
      skip: (page - 1) * pageSize,
      take: pageSize,
      select: LESSON_SELECT,
    }),
    db.lesson.count({ where }),
  ]);

  return {
    rows: rows.map((row) => toLessonSummary(row, settings.timezone)),
    total,
    page,
    pageSize,
  };
}

/** One lesson, with the roster size the register will show. */
export async function getLesson(
  ctx: AccessContext,
  lessonId: string,
  db: Db = prisma,
): Promise<LessonDetail> {
  requirePermission(ctx, 'schedule.view');

  // Tenancy, branch and "is this mine" all live in the SAME `where` as the id.
  // Fetching first and checking after would confirm the existence of another
  // branch's lesson to anyone who can guess an id.
  return loadLessonDetail(ctx, db, lessonId, {
    ...(composeReadFilter(ctx, {
      selfFilter: teacherLessonFilter(ctx),
      escapeHatch: 'schedule.viewAll',
    }) as object),
  });
}

