/**
 * Concrete lessons: materialising them from the timetable, and the exceptions.
 *
 * A `Lesson` is the dated instance attendance, homework and grades hang off. Two
 * things about this file matter more than the rest:
 *
 * GENERATION IS IDEMPOTENT. `generateLessons` may be run by a cron, by an
 * administrator pressing a button, and by both at once. The unique index on
 * (groupId, startsAt) is what makes that safe rather than merely unlikely: the
 * insert uses `skipDuplicates`, and the run reports created vs skipped instead of
 * failing. Re-running over the same range creates nothing.
 *
 * AN EXCEPTION IS A RECORD, NOT A DELETION. A cancelled lesson keeps its row with
 * a reason; a rescheduled one keeps its identity so the attendance already
 * attached to it does not become an orphan. Nothing here deletes a Lesson.
 */

