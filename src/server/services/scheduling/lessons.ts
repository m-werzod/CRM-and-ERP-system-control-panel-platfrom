/**
 * The instant a local wall-clock minute falls on.
 *
 * `zonedWallClockToInstant` resolves the offset from the zone database for that
 * particular date, which is the whole point: a class at 09:00 local stays at
 * 09:00 local across a DST transition instead of jumping to 08:00 or 10:00 as it
 * would if lessons were generated by adding fixed durations to a first instant.
 * A window ending at 24:00 is expressed as midnight on the following day, because
 * there is no 24:00 wall clock to convert.
 */
function instantFor(date: DateOnly, minute: number, zone: TimeZone): Date {
  return minute === MINUTES_IN_DAY
    ? zonedWallClockToInstant(addDaysToDateOnly(date, 1), 0, zone)
    : zonedWallClockToInstant(date, minute, zone);
}

/** `${groupId}|${startsAt}` — the shape of the (groupId, startsAt) unique index. */
function lessonKey(groupId: string, startsAt: Date): string {
  return `${groupId}|${startsAt.getTime()}`;
}

