/**
 * The first screen a teacher sees on a phone: today's classes, with enough on
 * each card to decide what to tap.
 *
 * TWO queries, always. The lessons come back in one; the roster sizes come back
 * in one grouped count keyed by group, because "how many students are enrolled on
 * this date" is a dated question the relation count cannot express — and asking it
 * per lesson would be the N+1 this endpoint can least afford.
 */
export async function getTodaysLessonsForTeacher(
  ctx: AccessContext,
  input: { readonly date?: DateOnly; readonly teacherId?: string } = {},
  db: Db = prisma,
): Promise<TeacherDay> {
  requirePermission(ctx, 'schedule.view');

  const ownTeacherId = ctx.self.teacherId;
  const mayViewOthers = ctx.isSystem || can(ctx, 'schedule.viewAll');

  if (input.teacherId && input.teacherId !== ownTeacherId && !mayViewOthers) {
    throw new ForbiddenError("You can only open your own timetable.");
  }
  const teacherId = input.teacherId ?? ownTeacherId;
  if (!teacherId) {
    throw new ForbiddenError('This account is not linked to a teacher.');
  }

  const settings = await getSettings(['timezone'], { organizationId: ctx.organizationId }, db);
  const date = input.date ?? todayIn(settings.timezone);
  const on = dateOnlyToPrismaDate(date);

  const lessons = await db.lesson.findMany({
    where: {
      ...scopeFilter(ctx),
      lessonDate: on,
      // A lesson moved to another day is no longer part of this day; a cancelled
      // one stays visible so the teacher knows not to turn up for it.
      status: { not: 'RESCHEDULED' },
      OR: [
        { teacherId },
        { group: { teacherAssignments: { some: { teacherId, endDate: null } } } },
      ],
    },
    orderBy: { startsAt: 'asc' },
    select: {
      id: true,
      groupId: true,
      startsAt: true,
      endsAt: true,
      status: true,
      attendanceStatus: true,
      topic: true,
      group: { select: { name: true, code: true } },
      room: { select: { name: true } },
      subject: { select: { name: true } },
      _count: { select: { attendanceRecords: true } },
    },
  });

  if (lessons.length === 0) {
    return { date, timezone: settings.timezone, teacherId, lessons: [] };
  }

  const rosterSizes = await db.enrollment.groupBy({
    by: ['groupId'],
    where: {
      groupId: { in: [...new Set(lessons.map((lesson) => lesson.groupId))] },
      startDate: { lte: on },
      OR: [{ endDate: null }, { endDate: { gte: on } }],
      student: { deletedAt: null },
    },
    _count: { _all: true },
  });
  const enrolledByGroup = new Map(rosterSizes.map((row) => [row.groupId, row._count._all]));

  return {
    date,
    timezone: settings.timezone,
    teacherId,
    lessons: lessons.map((lesson) => ({
      id: lesson.id,
      groupId: lesson.groupId,
      groupName: lesson.group.name,
      groupCode: lesson.group.code,
      subjectName: lesson.subject?.name ?? null,
      roomName: lesson.room?.name ?? null,
      startsAt: lesson.startsAt,
      endsAt: lesson.endsAt,
      startTime: formatTime(lesson.startsAt, settings.timezone),
      endTime: formatTime(lesson.endsAt, settings.timezone),
      status: lesson.status,
      attendanceStatus: lesson.attendanceStatus,
      registerSubmitted:
        lesson.attendanceStatus === 'SUBMITTED' || lesson.attendanceStatus === 'APPROVED',
      enrolledCount: enrolledByGroup.get(lesson.groupId) ?? 0,
      markedCount: lesson._count.attendanceRecords,
      topic: lesson.topic,
    })),
  };
}
