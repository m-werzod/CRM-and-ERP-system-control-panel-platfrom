export interface GenerateLessonsInput {
  /** Defaults to today in the organisation timezone. */
  readonly fromDate?: DateOnly;
  /** Defaults to the configured horizon; clamped to it when further out. */
  readonly throughDate?: DateOnly;
  readonly branchId?: string | null;
  readonly groupId?: string | null;
  readonly slotId?: string | null;
}

export interface GenerateLessonsResult {
  readonly from: DateOnly;
  readonly to: DateOnly;
  readonly slotsConsidered: number;
  readonly candidates: number;
  readonly created: number;
  /** Already present — the idempotent case, not an error. */
  readonly skippedExisting: number;
  /** Blocked by a teacher, room or group clash with something already booked. */
  readonly skippedConflicting: number;
  /** A sample of the blocking clashes, for an operator to act on. */
  readonly conflicts: readonly ScheduleConflict[];
  readonly clampedToHorizon: boolean;
  readonly horizonWeeks: number;
}

const CONFLICT_SAMPLE_LIMIT = 20;

/**
 * Materialise `Lesson` rows from the active timetable over a date range.
 *
 * A candidate that clashes is SKIPPED and reported, not thrown: aborting a whole
 * term's generation because one room was double-booked by an ad-hoc lesson would
 * leave the timetable half-built, and the operator needs the list of problems
 * rather than the first one.
 */
export async function generateLessons(
  ctx: AccessContext,
  input: GenerateLessonsInput = {},
  db?: Db,
): Promise<GenerateLessonsResult> {
  requirePermission(ctx, 'schedule.generateLessons');

  // READ COMMITTED, unlike the single-write paths. This is a long bulk job that
  // touches most of the term's rows, so Serializable would abort it whenever an
  // administrator happened to save a lesson; and the guard it actually relies on
  // is the (groupId, startsAt) unique index plus `skipDuplicates`, not isolation.
  // Generation reports clashes rather than enforcing them, so a lost race here
  // costs a re-run, not a corrupted timetable.
  return withTransaction(
    async (tx) => {
      const settings = await getSettings(
        ['timezone', 'lessonGenerationHorizonWeeks'],
        { organizationId: ctx.organizationId, branchId: input.branchId ?? null },
        tx,
      );
      const zone = settings.timezone;
      const horizonWeeks = settings.lessonGenerationHorizonWeeks;

      const from = input.fromDate ?? todayIn(zone);
      // The horizon is a hard ceiling, not a default: a caller asking for three
      // years of lessons would otherwise write a million rows nobody reviewed.
      const horizonEnd = addDaysToDateOnly(from, horizonWeeks * 7 - 1);
      const requested = input.throughDate ?? horizonEnd;
      const to = requested > horizonEnd ? horizonEnd : requested;

      if (to < from) {
        throw new BusinessRuleError(
          'schedule.range_inverted',
          'The generation range ends before it starts.',
          { details: { from, to: requested } },
        );
      }

      const empty: GenerateLessonsResult = {
        from,
        to,
        slotsConsidered: 0,
        candidates: 0,
        created: 0,
        skippedExisting: 0,
        skippedConflicting: 0,
        conflicts: [],
        clampedToHorizon: to !== requested,
        horizonWeeks,
      };

      const slots = await loadGenerableSlots(
        ctx,
        tx,
        { from, to },
        { branchId: input.branchId, groupId: input.groupId, slotId: input.slotId },
      );
      if (slots.length === 0) return empty;

      // ---- candidates ---------------------------------------------------
      const candidates: Array<{
        readonly slotId: string;
        readonly branchId: string;
        readonly groupId: string;
        readonly teacherId: string | null;
        readonly roomId: string | null;
        readonly subjectId: string | null;
        readonly lessonDate: DateOnly;
        readonly startsAt: Date;
        readonly endsAt: Date;
        readonly labels: { group: string };
      }> = [];

      for (const slot of slots) {
        // Intersect the requested range with the slot's own effective range and
        // the group's run dates; a slot cannot produce lessons before its group
        // starts or after it finishes.
        const groupStart = slot.group.startDate ? prismaDateToDateOnly(slot.group.startDate) : null;
        const groupEnd = slot.group.endDate ? prismaDateToDateOnly(slot.group.endDate) : null;

        const windowFrom = [from, slot.effectiveFrom, groupStart]
          .filter((value): value is DateOnly => value !== null)
          .reduce((a, b) => (a > b ? a : b));
        const windowTo = [to, slot.effectiveTo, groupEnd]
          .filter((value): value is DateOnly => value !== null)
          .reduce((a, b) => (a < b ? a : b));
        if (windowTo < windowFrom) continue;

        for (const date of datesMatchingWeekdays(windowFrom, windowTo, [slot.dayOfWeek], zone)) {
          candidates.push({
            slotId: slot.id,
            branchId: slot.branchId,
            groupId: slot.groupId,
            teacherId: slot.teacherId,
            roomId: slot.roomId,
            subjectId: slot.subjectId,
            lessonDate: date,
            startsAt: instantFor(date, slot.startMinute, zone),
            endsAt: instantFor(date, slot.endMinute, zone),
            labels: { group: slot.group.name },
          });
        }
      }

      if (candidates.length === 0) {
        return { ...empty, slotsConsidered: slots.length };
      }

      // ---- what is already booked, in ONE query -------------------------
      const groupIds = [...new Set(candidates.map((c) => c.groupId))];
      const teacherIds = [
        ...new Set(candidates.map((c) => c.teacherId).filter((id): id is string => id !== null)),
      ];
      const roomIds = [
        ...new Set(candidates.map((c) => c.roomId).filter((id): id is string => id !== null)),
      ];
      const { from: rangeStart, toExclusive: rangeEnd } = dayRangeToInstants(from, to, zone);

      const existingRows = await tx.lesson.findMany({
        where: {
          organizationId: ctx.organizationId,
          // Half-open overlap with the whole generation window.
          startsAt: { lt: rangeEnd },
          endsAt: { gt: rangeStart },
          OR: [
            { groupId: { in: groupIds } },
            ...(teacherIds.length > 0 ? [{ teacherId: { in: teacherIds } }] : []),
            ...(roomIds.length > 0 ? [{ roomId: { in: roomIds } }] : []),
          ],
        },
        select: {
          id: true,
          groupId: true,
          teacherId: true,
          roomId: true,
          startsAt: true,
          endsAt: true,
          status: true,
        },
      });

      // Cancelled lessons are deliberately NOT filtered out of the query: they
      // free their room (so the conflict index drops them) but they still occupy
      // the unique index, so re-generating must recognise them as already
      // existing rather than try to recreate them and resurrect a cancelled class.
      const existingKeys = new Set(existingRows.map((row) => lessonKey(row.groupId, row.startsAt)));
      const index = indexLessonsForConflicts(existingRows);

      const toCreate: Prisma.LessonCreateManyInput[] = [];
      const conflictSample: ScheduleConflict[] = [];
      let skippedExisting = 0;
      let skippedConflicting = 0;

      for (const candidate of candidates) {
        const key = lessonKey(candidate.groupId, candidate.startsAt);
        if (existingKeys.has(key)) {
          skippedExisting += 1;
          continue;
        }

        const conflicts = findLessonConflictsInIndex(candidate, index);
        if (conflicts.length > 0) {
          skippedConflicting += 1;
          for (const conflict of conflicts) {
            if (conflictSample.length < CONFLICT_SAMPLE_LIMIT) conflictSample.push(conflict);
          }
          continue;
        }

        toCreate.push({
          organizationId: ctx.organizationId,
          branchId: candidate.branchId,
          groupId: candidate.groupId,
          teacherId: candidate.teacherId,
          roomId: candidate.roomId,
          subjectId: candidate.subjectId,
          scheduleSlotId: candidate.slotId,
          lessonDate: dateOnlyToPrismaDate(candidate.lessonDate),
          startsAt: candidate.startsAt,
          endsAt: candidate.endsAt,
        });

        // Accepted candidates join the index so two patterns that (wrongly) share
        // a room cannot both be generated in one run.
        existingKeys.add(key);
        addToLessonConflictIndex(index, {
          id: `pending:${key}`,
          groupId: candidate.groupId,
          teacherId: candidate.teacherId,
          roomId: candidate.roomId,
          startsAt: candidate.startsAt,
          endsAt: candidate.endsAt,
        });
      }

      // `skipDuplicates` closes the race with a concurrent generation run: the
      // unique index turns the loser's rows into no-ops instead of an error.
      const inserted =
        toCreate.length > 0
          ? await tx.lesson.createMany({ data: toCreate, skipDuplicates: true })
          : { count: 0 };

      const result: GenerateLessonsResult = {
        from,
        to,
        slotsConsidered: slots.length,
        candidates: candidates.length,
        created: inserted.count,
        skippedExisting: skippedExisting + (toCreate.length - inserted.count),
        skippedConflicting,
        conflicts: conflictSample,
        clampedToHorizon: to !== requested,
        horizonWeeks,
      };

      await recordAudit(
        ctx,
        {
          action: AUDIT_ACTIONS.SCHEDULE_CHANGED,
          entityType: 'Lesson',
          branchId: input.branchId ?? null,
          summary: `Generated ${result.created} lesson(s) for ${from} to ${to} (${result.skippedExisting} already present, ${result.skippedConflicting} blocked)`,
          metadata: {
            from,
            to,
            slotsConsidered: result.slotsConsidered,
            candidates: result.candidates,
            created: result.created,
            skippedExisting: result.skippedExisting,
            skippedConflicting: result.skippedConflicting,
            clampedToHorizon: result.clampedToHorizon,
            groupId: input.groupId ?? null,
            slotId: input.slotId ?? null,
          },
        },
        tx,
      );

      if (result.skippedConflicting > 0) {
        logger.warn('scheduling.generation_conflicts', {
          requestId: ctx.requestId,
          organizationId: ctx.organizationId,
          from,
          to,
          skippedConflicting: result.skippedConflicting,
        });
      }

      return result;
    },
    { existing: db },
  );
}

