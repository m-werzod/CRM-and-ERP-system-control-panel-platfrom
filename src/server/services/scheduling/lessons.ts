export async function cancelLesson(
  ctx: AccessContext,
  input: { readonly lessonId: string; readonly reason: string },
  db?: Db,
): Promise<{ id: string; status: LessonStatus; attendanceStatus: LessonAttendanceStatus }> {
  requirePermission(ctx, 'schedule.cancelLesson');

  if (input.reason.trim().length < 3) {
    throw new BusinessRuleError(
      'schedule.cancellation_reason_required',
      'A cancellation must record why the lesson is not happening.',
    );
  }

  return withTransaction(
    async (tx) => {
      const lesson = await tx.lesson.findFirst({
        where: { id: input.lessonId, ...scopeFilter(ctx) },
        select: {
          id: true,
          branchId: true,
          groupId: true,
          lessonDate: true,
          startsAt: true,
          status: true,
          attendanceStatus: true,
          group: { select: { name: true } },
        },
      });
      if (!lesson) throw new NotFoundError('Lesson', input.lessonId);

      if (lesson.status === 'CANCELLED') {
        throw new StateInvalidError('lesson', 'already cancelled', 'cancelled');
      }
      if (lesson.attendanceStatus === 'SUBMITTED' || lesson.attendanceStatus === 'APPROVED') {
        // A lesson whose register has been signed off demonstrably happened.
        // Un-happening it would contradict attendance that students and parents
        // have already been shown; a correction is the right instrument.
        throw new StateInvalidError(
          'lesson',
          'already registered',
          'cancelled',
          'This lesson already has a submitted attendance register, so it cannot be cancelled. Correct the attendance instead.',
        );
      }

      await tx.lesson.update({
        where: { id: lesson.id },
        data: {
          status: 'CANCELLED',
          cancellationReason: input.reason,
          // NOT_REQUIRED takes the lesson off the "registers outstanding"
          // worklist and out of the attendance denominator: a class that did not
          // happen must not count against a student's attendance rate.
          attendanceStatus: 'NOT_REQUIRED',
        },
      });

      await recordAudit(
        ctx,
        {
          action: AUDIT_ACTIONS.LESSON_CANCELLED,
          entityType: 'Lesson',
          entityId: lesson.id,
          branchId: lesson.branchId,
          summary: `Lesson cancelled for ${lesson.group.name} on ${prismaDateToDateOnly(lesson.lessonDate)}`,
          reason: input.reason,
          severity: 'NOTICE',
          metadata: { startsAt: toIso(lesson.startsAt), previousStatus: lesson.status },
          timeline: {
            subjectType: 'GROUP',
            subjectId: lesson.groupId,
            type: 'schedule.lesson.cancelled',
            title: `Lesson on ${prismaDateToDateOnly(lesson.lessonDate)} cancelled`,
            description: input.reason,
          },
        },
        tx,
      );

      return { id: lesson.id, status: 'CANCELLED', attendanceStatus: 'NOT_REQUIRED' };
    },
    { existing: db },
  );
}

