export interface RescheduleLessonInput {
  readonly lessonId: string;
  /** Any field left out keeps its current value. */
  readonly lessonDate?: DateOnly;
  readonly startMinute?: number;
  readonly endMinute?: number;
  readonly teacherId?: string | null;
  readonly roomId?: string | null;
  readonly reason: string;
}

/**
 * Move a lesson, keeping its identity.
 *
 * The same row moves rather than being replaced, because attendance, homework and
 * grades reference `lessonId`; replacing it would orphan them. The change is
 * audited field by field, so "why is Tuesday's class at 14:00 now" has an answer.
 */
export async function rescheduleLesson(
  ctx: AccessContext,
  input: RescheduleLessonInput,
  db?: Db,
): Promise<LessonDetail> {
  requirePermission(ctx, 'schedule.cancelLesson');

  if (input.reason.trim().length < 3) {
    throw new BusinessRuleError(
      'schedule.reschedule_reason_required',
      'A reschedule must record why the lesson is moving.',
    );
  }

  // Serializable, not because money moves, but because the invariant has no
  // database constraint behind it: two administrators booking the same room at
  // the same instant would both read a clear check and both write under READ
  // COMMITTED. Write skew is the exact anomaly, and there is no unique index to
  // catch the loser.
  return withSerializableRetry(
    async (tx) => {
      const lesson = await tx.lesson.findFirst({
        where: { id: input.lessonId, ...scopeFilter(ctx) },
        select: {
          id: true,
          branchId: true,
          groupId: true,
          teacherId: true,
          roomId: true,
          subjectId: true,
          scheduleSlotId: true,
          lessonDate: true,
          startsAt: true,
          endsAt: true,
          status: true,
          attendanceStatus: true,
        },
      });
      if (!lesson) throw new NotFoundError('Lesson', input.lessonId);

      if (lesson.status === 'CANCELLED') {
        throw new StateInvalidError('lesson', 'cancelled', 'rescheduled');
      }
      if (lesson.attendanceStatus === 'SUBMITTED' || lesson.attendanceStatus === 'APPROVED') {
        throw new StateInvalidError(
          'lesson',
          'already registered',
          'rescheduled',
          'This lesson already has a submitted attendance register and cannot be moved.',
        );
      }

      const teacherId = input.teacherId === undefined ? lesson.teacherId : input.teacherId;
      const roomId = input.roomId === undefined ? lesson.roomId : input.roomId;

      const resources = await resolveResources(
        ctx,
        { groupId: lesson.groupId, teacherId, roomId, subjectId: lesson.subjectId },
        tx,
        'lesson',
      );
      const zone = resources.timezone;

      const lessonDate = input.lessonDate ?? prismaDateToDateOnly(lesson.lessonDate);
      const startMinute = input.startMinute ?? instantToWallClockMinute(lesson.startsAt, zone);
      const endMinute = input.endMinute ?? instantToWallClockMinute(lesson.endsAt, zone);
      assertMinuteWindow(startMinute, endMinute);

      const startsAt = instantFor(lessonDate, startMinute, zone);
      const endsAt = instantFor(lessonDate, endMinute, zone);

      await assertSlotIsFree(
        ctx,
        tx,
        lessonAsSlotCandidate({
          groupId: lesson.groupId,
          teacherId,
          roomId,
          dayOfWeek: weekdayOf(lessonDate, zone),
          startMinute,
          endMinute,
          onDate: lessonDate,
          labels: resources.labels,
        }),
        // The lesson's own pattern still reserves the hour it came from, and a
        // small move inside that window would otherwise clash with the very slot
        // this lesson is an instance of.
        lesson.scheduleSlotId,
      );

      await assertLessonIsFree(ctx, tx, {
        id: lesson.id,
        groupId: lesson.groupId,
        teacherId,
        roomId,
        startsAt,
        endsAt,
        labels: resources.labels,
      });

      await tx.lesson.update({
        where: { id: lesson.id },
        data: {
          lessonDate: dateOnlyToPrismaDate(lessonDate),
          startsAt,
          endsAt,
          teacherId,
          roomId,
        },
      });

      const detail = await loadLessonDetail(ctx, tx, lesson.id);

      await recordAudit(
        ctx,
        {
          action: AUDIT_ACTIONS.LESSON_RESCHEDULED,
          entityType: 'Lesson',
          entityId: lesson.id,
          branchId: lesson.branchId,
          summary: `Lesson for ${detail.groupName} moved to ${lessonDate} ${formatWallClock(startMinute)}`,
          reason: input.reason,
          severity: 'NOTICE',
          changes: diffFields(
            {
              lessonDate: prismaDateToDateOnly(lesson.lessonDate),
              startsAt: lesson.startsAt,
              endsAt: lesson.endsAt,
              teacherId: lesson.teacherId,
              roomId: lesson.roomId,
            },
            {
              lessonDate,
              startsAt,
              endsAt,
              teacherId,
              roomId,
            },
          ),
          timeline: {
            subjectType: 'GROUP',
            subjectId: lesson.groupId,
            type: 'schedule.lesson.rescheduled',
            title: `Lesson moved to ${lessonDate} at ${formatWallClock(startMinute)}`,
            description: input.reason,
          },
        },
        tx,
      );

      return detail;
    },
    { existing: db },
  );
}

