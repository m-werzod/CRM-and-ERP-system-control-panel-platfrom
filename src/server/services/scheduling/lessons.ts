export interface CreateAdHocLessonInput {
  readonly groupId: string;
  readonly lessonDate: DateOnly;
  readonly startMinute: number;
  readonly endMinute: number;
  readonly teacherId?: string | null;
  readonly roomId?: string | null;
  readonly subjectId?: string | null;
  readonly topic?: string | null;
  readonly lessonNumber?: number | null;
}

/**
 * A one-off lesson outside the pattern: a make-up class, an extra revision
 * session, a trial.
 *
 * Checked against BOTH levels. The instance check catches other lessons; the
 * pattern check catches a slot whose lessons have not been generated yet, which
 * is the case an instance-only check silently allows and is the reason the
 * schema's conflict note names both.
 */
export async function createAdHocLesson(
  ctx: AccessContext,
  input: CreateAdHocLessonInput,
  db?: Db,
): Promise<LessonDetail> {
  requirePermission(ctx, 'schedule.manage');

  // Serializable, not because money moves, but because the invariant has no
  // database constraint behind it: two administrators booking the same room at
  // the same instant would both read a clear check and both write under READ
  // COMMITTED. Write skew is the exact anomaly, and there is no unique index to
  // catch the loser.
  return withSerializableRetry(
    async (tx) => {
      assertMinuteWindow(input.startMinute, input.endMinute);

      const resources = await resolveResources(ctx, input, tx, 'lesson');
      assertGroupSchedulable(resources.group);

      const zone = resources.timezone;
      const startsAt = instantFor(input.lessonDate, input.startMinute, zone);
      const endsAt = instantFor(input.lessonDate, input.endMinute, zone);

      await assertSlotIsFree(
        ctx,
        tx,
        lessonAsSlotCandidate({
          groupId: input.groupId,
          teacherId: resources.teacherId,
          roomId: resources.roomId,
          dayOfWeek: weekdayOf(input.lessonDate, zone),
          startMinute: input.startMinute,
          endMinute: input.endMinute,
          onDate: input.lessonDate,
          labels: resources.labels,
        }),
      );

      await assertLessonIsFree(ctx, tx, {
        groupId: input.groupId,
        teacherId: resources.teacherId,
        roomId: resources.roomId,
        startsAt,
        endsAt,
        labels: resources.labels,
      });

      let created: { id: string };
      try {
        created = await tx.lesson.create({
          data: {
            organizationId: ctx.organizationId,
            branchId: resources.branchId,
            groupId: input.groupId,
            teacherId: resources.teacherId,
            roomId: resources.roomId,
            subjectId: resources.subjectId,
            lessonDate: dateOnlyToPrismaDate(input.lessonDate),
            startsAt,
            endsAt,
            topic: input.topic ?? null,
            lessonNumber: input.lessonNumber ?? null,
          },
          select: { id: true },
        });
      } catch (error) {
        // The (groupId, startsAt) unique index rejected a second lesson at the
        // same instant. Say so in a sentence an operator can act on.
        const code = (error as { code?: string }).code;
        if (code === 'P2002' || code === '23505') {
          throw new ConflictError(
            `${resources.group.name} already has a lesson starting at that time.`,
            { details: { groupId: input.groupId, startsAt: toIso(startsAt) } },
          );
        }
        throw error;
      }

      const detail = await loadLessonDetail(ctx, tx, created.id);

      await recordAudit(
        ctx,
        {
          action: AUDIT_ACTIONS.SCHEDULE_CHANGED,
          entityType: 'Lesson',
          entityId: detail.id,
          branchId: detail.branchId,
          summary: `Extra lesson added for ${detail.groupName} on ${detail.lessonDate} ${detail.startTime}–${detail.endTime}`,
          metadata: {
            groupId: detail.groupId,
            teacherId: detail.teacherId,
            roomId: detail.roomId,
            startsAt: toIso(startsAt),
            endsAt: toIso(endsAt),
          },
          timeline: {
            subjectType: 'GROUP',
            subjectId: detail.groupId,
            type: 'schedule.lesson.added',
            title: `Extra lesson on ${detail.lessonDate} at ${detail.startTime}`,
            description: input.topic ?? detail.roomName,
          },
        },
        tx,
      );

      return detail;
    },
    { existing: db },
  );
}

/** Load the lessons that could clash with a candidate, in one query, and check. */
async function assertLessonIsFree(
  ctx: AccessContext,
  db: Db,
  candidate: {
    readonly id?: string | null;
    readonly groupId: string;
    readonly teacherId: string | null;
    readonly roomId: string | null;
    readonly startsAt: Date;
    readonly endsAt: Date;
    readonly labels?: { group?: string | null; teacher?: string | null; room?: string | null };
  },
): Promise<void> {
  const rows = await db.lesson.findMany({
    where: {
      organizationId: ctx.organizationId,
      ...(candidate.id ? { id: { not: candidate.id } } : {}),
      status: { notIn: [...TIME_FREEING_LESSON_STATUSES] },
      // Half-open overlap, expressed in SQL so only real candidates are loaded.
      startsAt: { lt: candidate.endsAt },
      endsAt: { gt: candidate.startsAt },
      OR: [
        { groupId: candidate.groupId },
        ...(candidate.teacherId ? [{ teacherId: candidate.teacherId }] : []),
        ...(candidate.roomId ? [{ roomId: candidate.roomId }] : []),
      ],
    },
    select: {
      id: true,
      groupId: true,
      teacherId: true,
      roomId: true,
      startsAt: true,
      endsAt: true,
      status: true,
    },
  });

  const conflicts = findLessonConflictsInIndex(candidate, indexLessonsForConflicts(rows));
  if (conflicts.length > 0) throw new ScheduleConflictError(conflicts);
}

